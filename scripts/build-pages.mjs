import {cp,mkdir,readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url));
const output=new URL('../pages-dist/',import.meta.url);
await mkdir(output,{recursive:true});
await cp(new URL('../public/game/',import.meta.url),new URL('game/',output),{recursive:true});
const gameFile=new URL('game/index.html',output);
let html=await readFile(gameFile,'utf8');
const {apiBase}=JSON.parse(await readFile(new URL('../config/leaderboard.json',import.meta.url),'utf8'));
const endpoint=new URL(apiBase);
if(endpoint.protocol!=='https:'||endpoint.username||endpoint.password||endpoint.search||endpoint.hash)throw new Error('Invalid leaderboard endpoint.');
html=html.replace('<head>',`<head><meta name="softserve-api-origin" content="${endpoint.href}">`);
await writeFile(gameFile,html);
const revision=html.match(/game\.js\?v=([^"']+)/)?.[1];
if(!revision)throw new Error('Missing game asset revision.');
await writeFile(new URL('index.html',output),`<!doctype html><html lang="zh-Hans"><head><meta charset="UTF-8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover"><meta name="theme-color" content="#fff8ec"><title>冰淇淋模拟器</title><meta name="author" content="kai"><meta name="description" content="按住出奶油，自由卷出你的冰淇淋。六款皮肤，总榜与每日榜。"><style>html,body{width:100%;height:100%;margin:0;background:#fff8ec;overflow:hidden}iframe{display:block;width:min(100%,520px);height:100dvh;margin:auto;border:0}</style></head><body><iframe src="./game/index.html?v=${encodeURIComponent(revision)}" title="冰淇淋模拟器" allow="web-share"></iframe></body></html>`);
await writeFile(new URL('.nojekyll',output),'');
console.log('Static game ready: '+root+'pages-dist/');
